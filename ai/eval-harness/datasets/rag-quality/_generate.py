def make_case(subset: str, idx: int, q: str, citations: list[str],
              concepts: list[str], faith: float, refused: bool, desc: str) -> dict:
    expected = {
        "required_citations": citations,
        "required_concepts": concepts,
        "faithfulness_minimum": faith,
        "refused": refused,
    }
    tags = ["rag-quality", subset, "synthetic"]
    if refused:
        tags.append("adversarial")
    return {
        "id": f"rag-quality-{subset}-{idx + 1:03d}",
        "agent": "rag",
        "input": {
            "question": q,
            "tenant_id": "tnt_demo",
        },
        "expected": expected,
        "tags": tags,
        "description": desc,
    }


def main():
    _ = random.Random(20260426)
    here = Path(__file__).parent

    cases = []
    for i, c in enumerate(CASES_115FZ):
        cases.append(make_case("115fz", i, *c))
    for i, c in enumerate(CASES_375P):
        cases.append(make_case("375p", i, *c))
    for i, c in enumerate(CASES_499P):
        cases.append(make_case("499p", i, *c))
    for i, c in enumerate(CASES_590P):
        cases.append(make_case("590p", i, *c))
    for i, c in enumerate(CASES_ADVERSARIAL):
        cases.append(make_case("adversarial", i, *c))

    (here / "rag-cases.json").write_text(
        json.dumps(cases, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(cases)} rag-quality cases")


if __name__ == "__main__":
    main()
