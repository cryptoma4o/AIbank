# Простейший детектор prompt-injection в вопросе. Не пытается быть строгим
# фильтром — это лишь первая линия (defence-in-depth), реальный гардрейл
# делает aidefence (см. docs/security-architecture.md § 5.4).
_INJECTION_TRIGGERS = (
    "ignore previous",
    "ignore the previous",
    "забудь предыдущ",
    "забудь все инструкции",
    "проигнорируй инструкц",
    "system prompt",
    "системный промпт",
    "ты теперь",
    "ты больше не",
    "act as",
    "веди себя как",
)


def looks_like_injection(question: str) -> bool:
    q = question.lower()
    return any(trigger in q for trigger in _INJECTION_TRIGGERS)
